let lang: Lang = 'tr';
export const setLang = (l: Lang) => (lang = l);
export const getLang = () => lang;

export function t(key: StringKey, p: Record<string, string | number> = {}): string {
  return (lang === 'tr' ? tr : en)[key].replace(/\{(\w+)\}/g, (_, k: string) =>
    String(p[k] ?? `{${k}}`),
  );
}
